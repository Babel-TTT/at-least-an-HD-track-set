/** 文本在给定缩放下占多少像素宽 */
export function textWidth(text, scale = 1) {
  return text.length ? (text.length * ADVANCE - 1) * scale : 0;
}

/**
 * 往 RGBA 缓冲里画一行文本。
 * 不认识的字符按空格处理（不会抛错 —— 诊断图不该因为一个怪字符就崩）。
 *
 * @param {Uint8Array} px   RGBA 缓冲
 * @param {number} W        缓冲宽
 * @param {number} H        缓冲高
 * @param {number} x,y      左上角
 * @param {string} text     文本（内部会转大写）
 * @param {number} scale    放大倍数
 * @param {number[]} rgb    颜色
 */
export function drawText(px, W, H, x, y, text, scale = 1, rgb = [255, 255, 255]) {
  const s = String(text).toUpperCase();
  for (let n = 0; n < s.length; n++) {
    const rows = (G[s[n]] ?? G[' ']).split(',');
    const gx = x + n * ADVANCE * scale;
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (rows[r][c] !== '1') continue;
        for (let dy = 0; dy < scale; dy++) {
          for (let dx = 0; dx < scale; dx++) {
            const qx = gx + c * scale + dx, qy = y + r * scale + dy;
            if (qx < 0 || qy < 0 || qx >= W || qy >= H) continue;
            const i = (qy * W + qx) * 4;
            px[i] = rgb[0]; px[i + 1] = rgb[1]; px[i + 2] = rgb[2]; px[i + 3] = 255;
          }
        }
      }
    }
  }
}
