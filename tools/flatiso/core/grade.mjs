// 色彩分级（grade）：解析之后、写像素之前跑的一层后处理。
//
// 为什么需要它
// ------------
// 只有"平面着色 + 半球环境光"出来的图，问题不是不好看，而是**不够风格化**：
// 明暗对比偏软、颜色偏灰、整体像一张建筑效果图而不是一张游戏素材。
// 这一步把这些补回去 —— 全部在**显示空间**做，不碰线性光照计算。
//
// 四件事，按顺序：
//   1. 对比    —— 以 pivot 为支点拉开明暗
//   2. 分档    —— 每通道吸附到 N 级格点（可选）
//   3. 饱和度  —— 整体加一点色
//   4. 分离调色 —— 阴影往冷偏、高光往暖偏（这一步最出"风格"）
//
// 关于 pivot 为什么要可调
// ----------------------
// 第一版把支点写死在 0.5，结果**对比反而变小了**：我们的图整体偏亮
// （大片墙面落在 0.55~0.9），支点在 0.5 时两侧都被往上推，
// 0.60 和 0.895 被推成 0.648 和 0.945，差距从 0.295 缩到 0.297。
// 支点必须落在图的实际中调上（这里约 0.68）才会真正拉开：
//   0.60 → 0.578，0.895 → 0.955，差距 0.377。
//
// 本模块只负责**把参数算成常量**；逐像素的算式内联在 raster.mjs 里，
// 避免每个像素都分配对象。所有系数都可以在 look 预设里改。

export function makeGrade(o = {}) {
  const g = {
    contrast: o.contrast ?? 1,          // 对比系数 k，1 = 不变；1.25~1.40 是"明显但不爆"
    pivot: o.pivot ?? 0.68,             // 对比支点：应落在图的实际中调上
    steps: o.steps ?? 0,                // 每通道分档级数，0 = 关
    stepPull: o.stepPull ?? 0,          // 往格点拉的比例，0~1
    saturation: o.saturation ?? 1,
    splitAmount: o.splitAmount ?? 0,
    shadowTint: o.shadowTint ?? [0, 0, 0],
    highlightTint: o.highlightTint ?? [0, 0, 0],
  };
  g.enabled = g.contrast !== 1 || g.steps > 0 || g.saturation !== 1 || g.splitAmount !== 0;
  return g;
}

export const NEUTRAL = makeGrade();
